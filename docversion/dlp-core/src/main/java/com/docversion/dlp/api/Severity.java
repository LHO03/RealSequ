package com.docversion.dlp.api;

/**
 * 심각도. 화면 표시와 정렬을 위한 등급이다. (RD-SRS-5.4)
 *
 * <p>판정 자체는 점수 합산으로 이루어지며(→ {@link ScanResult#totalScore()}),
 * 이 등급은 점수를 사람이 읽을 수 있는 형태로 환산한 것이다.
 * 규칙별 심각도는 규칙 정의에 함께 보관한다.
 */
public enum Severity {

    /** 단독으로 민감 판정을 확정하는 수준. 주민등록번호, 신용카드번호 등. */
    HIGH,

    /** 문맥에 따라 민감할 수 있는 수준. 계좌번호 등. */
    MEDIUM,

    /** 단독으로는 부족하며 다른 항목과 함께일 때 의미를 갖는 수준. 전화번호, 이메일 등. */
    LOW
}
