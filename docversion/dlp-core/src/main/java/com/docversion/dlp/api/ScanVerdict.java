package com.docversion.dlp.api;

/**
 * 검사 판정. (RD-SRS-5.1)
 *
 * <p>{@link #UNDETERMINED}를 별도 값으로 둔 이유가 이 열거형의 핵심이다.
 * 텍스트 추출에 실패했거나 형식을 지원하지 않는 문서를 NOT_SENSITIVE로 처리하면
 * 검사되지 않은 문서가 "안전함"으로 표시되어 유출 차단이 무력화된다.
 * 판정 불가와 민감하지 않음은 반드시 구분한다.
 */
public enum ScanVerdict {

    /** 민감 데이터가 탐지되었다. 총점이 임계값을 넘은 경우. */
    SENSITIVE,

    /** 검사를 수행했으나 민감 데이터가 탐지되지 않았다. */
    NOT_SENSITIVE,

    /**
     * 검사를 수행할 수 없었다. 추출 실패, 형식 미지원, 엔진 오류 등.
     * 이 상태는 안전을 의미하지 않으며, 운영 정책에 따라 전체 재검사 또는
     * 수동 확인 대상으로 넘긴다.
     */
    UNDETERMINED
}
