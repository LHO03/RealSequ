package com.docversion.dlp.api;

/**
 * 검사 범위. 어떤 텍스트를 대상으로 검사했는지를 구분한다. (RD-SRS-5.1 / 5.2)
 *
 * <p>두 범위는 서로 다른 질문에 답하므로 결과를 각각 보관한다.
 * 클라이언트가 차단 판단(RD-SRS-5.3)에 사용하는 값은 {@link #FULL}이다.
 */
public enum ScanScope {

    /**
     * 해당 버전의 전체 텍스트를 검사한다. (RD-SRS-5.1)
     * "이 문서는 지금 민감한가"에 답하며, 판정의 정본이다.
     */
    FULL,

    /**
     * 이전 버전과의 차이 중 추가된 부분만 검사한다. (RD-SRS-5.2)
     * "이번 수정으로 민감 데이터가 새로 들어왔는가"에 답한다.
     *
     * <p>입력은 9.4 버전 비교(DiffService)가 산출한 결과에서 추가된 줄만 추려 만든다.
     * 별도 전처리기를 두지 않는다.
     *
     * <p>주의: 이 범위만으로는 이전 버전에 이미 있던 민감 데이터를 놓친다.
     * 반드시 FULL과 함께 사용해야 하며 단독으로 차단 판단에 쓰지 않는다.
     */
    DELTA
}
