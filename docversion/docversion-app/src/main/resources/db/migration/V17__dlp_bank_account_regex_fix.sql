-- V17: 계좌번호 규칙이 휴대전화번호를 잡는 문제 수정 (RD-SRS-5.4)
--
--   증상
--     문서에 "연락처: 010-1234-5678"과 "급여계좌: 국민은행 123-45-678901"이
--     함께 있으면 전화번호가 계좌번호로도 탐지되었다.
--
--   원인
--     계좌번호 정규식 \b\d{2,6}[- ]\d{2,6}[- ]\d{2,6}\b 은
--     010-1234-5678 형태에도 부합한다(3-4-4 자리). 문맥 조건은 앞뒤 40자를
--     보므로 근처에 은행명이 있으면 조건까지 통과한다.
--
--   영향
--     같은 문자열이 계좌번호(80점)와 전화번호(20점)로 이중 집계되어
--     점수가 부풀려지고, 탐지 목록에 전화번호가 계좌번호로 보고되어
--     담당자가 판단을 그르칠 수 있었다.
--
--   수정
--     계좌번호 정규식 앞에 부정형 전방탐색을 두어 휴대전화번호 형태를
--     제외한다. 엔진에도 구간 겹침 해소 로직을 함께 넣었으나, 그것은
--     일반적인 안전망이고 근본 원인은 규칙 자체에 있으므로 여기서 바로잡는다.
--
--   검증 (Java Pattern 기준)
--     010-1234-5678     → 제외
--     011-234-5678      → 제외
--     123-45-678901     → 탐지 (국민은행 형태)
--     1002-345-678901   → 탐지 (기업은행 형태)
--     352-0123-4567     → 탐지 (농협 형태)
-- ============================================================

UPDATE dlp_patterns
   SET regex = '\\b(?!01[0-9][-. ]?\\d{3,4}[-. ]?\\d{4}\\b)\\d{2,6}[- ]\\d{2,6}[- ]\\d{2,6}\\b',
       description = '문맥 조건 필수. 은행명 또는 거래 어휘가 앞뒤 40자 안에 있을 때만 탐지한다. 휴대전화번호(01X-XXXX-XXXX)는 부정형 전방탐색으로 제외한다.',
       updated_at = UNIX_TIMESTAMP()
 WHERE pattern_name = 'BANK_ACCOUNT';
