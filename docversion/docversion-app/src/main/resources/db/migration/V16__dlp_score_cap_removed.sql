-- V16: 점수 상한 제거 (RD-SRS-5.4)
--
--   V14에서 max_hits_scored 기본값을 3으로 두어 유형당 3건까지만
--   점수에 반영하도록 했다. 의도는 "전화번호 100개짜리 명부가 무한정
--   점수를 쌓지 않도록" 하는 것이었으나, 판정이 임계값 초과 여부만 보는
--   이진 판단이므로 상한은 판정 결과를 바꾸지 않는다.
--
--   오히려 정보를 지운다. 상한이 있으면 전화번호 3건 문서와 100건 명부가
--   똑같이 60점으로 기록되어, 실제로 더 위험한 명부를 구분할 수 없다.
--   개인정보가 대량으로 든 문서는 실제로 고위험이므로 점수가 높은 것이 맞다.
--
--   컬럼은 남긴다. 향후 특정 규칙에만 상한이 필요해지면 값만 넣으면 되고,
--   0은 무제한을 뜻하므로 현재는 아무 동작도 하지 않는다.
--
--   ※ V14는 이미 적용되어 flyway_schema_history에 체크섬이 기록되었으므로
--     수정하지 않고 별도 마이그레이션으로 변경한다.
-- ============================================================

-- 기존 5개 규칙의 상한 해제
UPDATE dlp_patterns SET max_hits_scored = 0, updated_at = UNIX_TIMESTAMP()
 WHERE max_hits_scored <> 0;

-- 앞으로 추가되는 규칙도 기본 무제한
ALTER TABLE dlp_patterns
    MODIFY COLUMN max_hits_scored INT NOT NULL DEFAULT 0
        COMMENT '점수에 반영할 최대 탐지 건수(0=무제한). 기본은 무제한이며 필요 시 규칙별로 지정';
