-- 1) 계좌번호: 오탐 14건의 원인 두 가지를 함께 제거한다
--
--   원인 A — 구분자가 공백을 허용했다
--     '\d{2,6}[- ]\d{2,6}[- ]\d{2,6}' 의 [- ] 는 공백도 받는다. 그래서 한 매칭이
--     공백을 건너뛰어 무관한 두 숫자열을 하나로 묶었다.
--       "입금 예정 금액은 1002-345 12-3456 두 건"  ->  '1002-345 12' 를 계좌번호로 탐지
--     한국 계좌번호는 하이픈으로 적는 것이 통례이므로 공백을 뺀다.
--
--   원인 B — 자릿수 하한이 없었다
--     최소 6자리면 통과해서 날짜·사번·유선번호·사업자등록번호가 모두 걸렸다.
--     실제 계좌번호는 11~14자리다. 반면 걸리던 것들은 8~10자리다.
--       날짜 2024-01-15(8) · 사번 12-3456-78(8) · 유선 02-1234-5678(10)
--       사업자등록번호 123-45-67890(10)
--     전체 길이 13자 이상(= 숫자 11자리 이상)을 요구하면 이들이 모두 빠진다.
--
--   덧붙인 두 가지
--     (?<!\+)   국가번호가 붙은 전화번호에서 시작하지 않게 한다.
--               "연락처 +82-10-1234-5678" 이 계좌번호로 잡히던 문제.
--     (?!-\d)   숫자 묶음이 더 이어지면 매칭하지 않는다. 긴 번호의 앞부분만
--               잘라 계좌번호로 보고하는 것을 막는다.
--
--   부수 효과 (측정 대상이 아니었으나 함께 나아진 것)
--     · 농협식 4묶음(352-0123-4567-89)을 온전히 탐지한다. 종전에는 앞 3묶음만 잘랐다.
--     · 유선번호 031-123-4567 이 더 이상 걸리지 않는다.
--
--   부수 효과 (나빠진 것 — 알고 감수한다)
--     · 공백으로 적은 계좌번호("123 45 678901")를 놓친다. 공백 허용이 오탐의
--       주된 통로였으므로 맞바꾼 것이다. 다음 측정에서 이 형태를 시험 문서로 넣어
--       실제로 문제가 되는지 확인한다(dlp-eval D02).
--
--   남은 약점 (측정으로 확인된 것이 아니라 검토 중 떠올린 것)
--     4묶음 숫자 식별자(주문번호 2024-1234-5678, ISBN 978-89-1234-567 등)는
--     자릿수만으로는 계좌번호와 구분되지 않는다. 은행 코드 대조가 없으면 어렵다.
--     추측으로 규칙을 더 좁히지 않고 시험 문서(dlp-eval C07·C08)로 남겨
--     다음 측정이 판단하게 한다.
--
--   검증 (Java Pattern 기준, 측정에 쓴 실제 문장으로 확인)
--     탐지되어야 하는 것
--       123-45-678901        국민         110-234-567890    신한
--       1002-345-678901      우리         352-0123-4567-89  농협(4묶음)
--       123456-78-901234     국민(6-2-6)  123-456789-01234  하나(3-6-5)
--     탐지되지 않아야 하는 것
--       2024-01-15           날짜         12-3456-78        사번
--       +82-10-1234-5678     국가번호     02-1234-5678      유선 대표번호
--       123-45-67890         사업자등록번호  031-123-4567     유선번호
--       010-1234-5678        휴대전화     1002-345 12-3456  공백 건너뛰기
-- ------------------------------------------------------------
UPDATE dlp_patterns
   SET regex = '(?<!\\+)\\b(?!01[0-9][-.]?\\d{3,4}[-.]?\\d{4}\\b)(?=[\\d-]{13})\\d{2,6}-\\d{2,6}-\\d{2,6}(?:-\\d{2,6})?\\b(?!-\\d)',
       description = '문맥 조건 필수(은행명·거래 어휘가 앞뒤 40자 안). 구분자는 하이픈만 인정하고 전체 13자 이상(숫자 11자리 이상)을 요구해 날짜·사번·유선번호·사업자등록번호를 배제한다. 휴대전화와 국가번호가 붙은 번호도 제외한다. 2026-08-31 탐지율 측정 결과 반영.',
       updated_at = UNIX_TIMESTAMP()
 WHERE pattern_name = 'BANK_ACCOUNT';

