-- 2) 신용카드: American Express 15자리를 탐지한다
--
--   원인
--     종전 정규식은 접두 뒤에 4자리 묶음 셋을 요구해 항상 16자리가 되었다.
--       (?:4\d{3}|5[1-5]\d{2}|6011|3[47]\d{2})[- ]?\d{4}[- ]?\d{4}[- ]?\d{4}
--     Amex 접두(34·37)는 인정하면서 자릿수에서 떨어져 나갔다. Amex는 15자리이며
--     4-6-5로 끊어 적는다. 측정에서 미탐 3건이 전부 이 형태였다.
--
--   수정
--     Amex 갈래를 앞에 두고 나머지 16자리 카드를 뒤에 둔다.
--     Luhn 검증기는 12~19자리를 받으므로 그대로 쓸 수 있다.
--
--   검증
--     3782-822463-10005  탐지 · Luhn 통과  (Amex 표준 시험번호)
--     378282246310005    탐지 (구분자 없음)
--     4539-5787-6362-1486 탐지 · Luhn 통과 (Visa, 종전과 동일)
--     5555-5555-5555-4444 탐지 (MasterCard, 종전과 동일)
--     1234-5678-9012-3456 미탐 (접두가 카드 대역이 아님)
-- ------------------------------------------------------------
UPDATE dlp_patterns
   SET regex = '\\b(?:3[47]\\d{2}[- ]?\\d{6}[- ]?\\d{5}|(?:4\\d{3}|5[1-5]\\d{2}|6011)[- ]?\\d{4}[- ]?\\d{4}[- ]?\\d{4})\\b',
       description = 'Luhn 검증 통과 시 100점, 형식만 맞으면 60점. Amex는 15자리(4-6-5), 그 외는 16자리(4-4-4-4). 2026-08-31 탐지율 측정 결과 반영.',
       updated_at = UNIX_TIMESTAMP()
 WHERE pattern_name = 'CREDIT_CARD';
