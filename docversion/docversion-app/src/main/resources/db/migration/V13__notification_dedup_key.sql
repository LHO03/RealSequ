-- ============================================================
-- V13: 알림 중복 방지 키의 의미 변경 (P1d, RD-SRS-9.9)
--
--   기존: dedup_key = 제목 + 파일 + 수신자 + (현재시각/300초)
--         5분이라는 "시간 구간"으로 동일 사건을 판정했다. 이 방식은 두 방향으로 부정확했다.
--           (1) 같은 제목의 서로 다른 사건을 동일 사건으로 오인 — 5분 안에 두 번 수정하면
--               두 번째 "새 버전" 알림이 조용히 사라졌다.
--           (2) 5분 경계를 넘기면 진짜 중복도 통과했다.
--
--   변경: dedup_key = 사건 식별자 + 수신자
--         사건 식별자는 이미 적재되는 이력 행의 일련번호를 쓴다.
--           - 새 버전      : ver:{versionId}
--           - 상태 변경    : st:{fileId}:h{상태이력 순번}
--           - 승인 워크플로: apr:{requestId}:a{판정이력 순번}:{종류}
--         이력 행은 사건 하나당 하나씩 생기므로 사건과 정확히 일대일이며,
--         판정 번복 후 재판정처럼 "같은 사람이 같은 행위를 반복"해도 번호가 달라진다.
--
--   컬럼 타입·인덱스는 그대로다(VARCHAR(255) + UNIQUE). 의미만 바뀌었으므로 주석을 갱신한다.
--   기존 행의 키는 옛 형식이지만, 새 형식과 충돌할 수 없어(접두사 체계가 다름) 그대로 둔다.
-- ============================================================

ALTER TABLE notifications
    MODIFY COLUMN dedup_key VARCHAR(255) DEFAULT NULL
        COMMENT '중복 방지 키 = 사건 식별자 + 수신자. UNIQUE + INSERT IGNORE';
